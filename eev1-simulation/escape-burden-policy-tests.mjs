import assert from 'node:assert/strict';
import {routeEscape,normalizeBurden,canAddInitialAction} from './escape-burden-policy.js';
let n=0;const t=f=>{f();n++;};
t(()=>assert.equal(routeEscape({escapeCode:'UNSURE'}).route,'ONE_NEUTRAL_CLARIFICATION'));
t(()=>assert.equal(routeEscape({escapeCode:'UNSURE',consecutiveUnsure:1}).route,'STOP_CLARIFYING_UNRESOLVED'));
t(()=>assert.equal(routeEscape({escapeCode:'NONE_FIT'}).route,'ONE_NEUTRAL_CLARIFICATION'));
t(()=>assert.equal(routeEscape({escapeCode:'NONE_FIT',clarificationAttempts:1}).route,'MOVE_ON_UNRESOLVED'));
t(()=>assert.equal(routeEscape({escapeCode:'PREFER_NOT_TO_ANSWER'}).route,'RESPECT_AND_MOVE_ON'));
t(()=>assert.equal(routeEscape({escapeCode:'SKIP_FOR_NOW'}).route,'DEFER_QUESTION'));
t(()=>assert.equal(routeEscape({escapeCode:'UNSURE',safetyPending:true}).route,'SAFETY_REVIEW'));
t(()=>assert.equal(routeEscape({escapeCode:'UNSURE'}).createsEvidence,false));
t(()=>assert.equal(routeEscape({escapeCode:'PREFER_NOT_TO_ANSWER'}).penalty,false));
t(()=>assert.throws(()=>routeEscape({escapeCode:'MAYBE'}),/invalid-escape-code/));
t(()=>assert.deepEqual(normalizeBurden({units:2,memberReportedBurden:'TOO_HIGH'}),{units:3,memberOverride:true}));
t(()=>assert.equal(normalizeBurden({units:2,memberReportedBurden:'LOWER_THAN_EXPECTED'}).units,1));
t(()=>assert.equal(canAddInitialAction({currentBurden:2,actionBurden:2}).reason,'INITIAL_BURDEN_CAP'));
t(()=>assert.equal(canAddInitialAction({currentBurden:1,actionBurden:1,duplicate:true}).reason,'DUPLICATE_ACTION'));
t(()=>assert.equal(canAddInitialAction({currentBurden:0,actionBurden:1,safetyBlocked:true}).reason,'SAFETY_BLOCK'));
t(()=>assert.equal(canAddInitialAction({currentBurden:2,actionBurden:1}).allowed,true));
console.log(`EEV1 escape/burden policy: PASS (${n} checks)`);
