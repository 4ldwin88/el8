import assert from 'node:assert/strict';
import {makeEvent,appendEvent,validateEventStream,rebuildProjection,auditChain} from './event-audit-contract.js';
let n=0;const t=f=>{f();n++;};
const mk=(id,seq,type='OBSERVATION_RECORDED')=>makeEvent({eventId:id,streamId:'member-1',sequence:seq,type,occurredAt:`2026-08-24T00:00:0${seq}Z`,recordedAt:`2026-08-24T00:00:1${seq}Z`,payload:{delta:1},provenance:{policyVersion:'eev1'}});
const e1=mk('e1',1),e2=mk('e2',2,'EVIDENCE_CREATED');
t(()=>assert.equal(Object.isFrozen(e1),true));
t(()=>assert.equal(Object.isFrozen(e1.payload),true));
t(()=>assert.deepEqual(appendEvent([],e1,{expectedSequence:0}),[e1]));
const s1=appendEvent([],e1,{expectedSequence:0});const s2=appendEvent(s1,e2,{expectedSequence:1});
t(()=>assert.equal(validateEventStream(s2).valid,true));
t(()=>assert.throws(()=>appendEvent(s1,e2,{expectedSequence:0}),/concurrency-conflict/));
t(()=>assert.throws(()=>appendEvent(s1,mk('e3',3),{expectedSequence:1}),/non-contiguous-sequence/));
t(()=>assert.throws(()=>appendEvent(s1,makeEvent({...e2,eventId:'e1'}),{expectedSequence:1}),/duplicate-event-id/));
t(()=>assert.throws(()=>appendEvent(s1,makeEvent({...e2,streamId:'member-2'}),{expectedSequence:1}),/stream-id-mismatch/));
t(()=>{const p=rebuildProjection(s2,(state,e)=>({count:(state.count??0)+e.payload.delta}),{});assert.equal(p.count,2);});
t(()=>{const a=auditChain(s2);assert.equal(a.length,2);assert.equal(a[1].provenance.policyVersion,'eev1');});
t(()=>{const bad=[e2,e1];assert.equal(validateEventStream(bad).valid,false);});
t(()=>assert.throws(()=>makeEvent({eventId:'x',streamId:'s',sequence:1,type:'BAD',occurredAt:'x',recordedAt:'x'}),/invalid-event/));
t(()=>{const before=JSON.stringify(s2);rebuildProjection(s2,(s,e)=>({...s,last:e.eventId}),{});assert.equal(JSON.stringify(s2),before);});
console.log(`EEV1 event/audit contract: PASS (${n} checks)`);
