import assert from 'node:assert/strict';
import {createPolicyCandidate,advanceCandidate,historicalSuggestion,rollbackDeployment,containsProtectedChange} from './learning-governance.js';
let n=0;const t=f=>{f();n++;};
const draft=createPolicyCandidate({candidateId:'c1',basePolicyVersion:'1.0',candidateVersion:'1.1',changes:[{domain:'PRIORITY_ORDER',change:'tie-break'}],metricsPlan:{primary:'decision-validity'},createdAt:'2026-08-24T00:00:00Z'});
t(()=>assert.equal(draft.stage,'DRAFT'));
t(()=>assert.equal(Object.isFrozen(draft),true));
t(()=>assert.throws(()=>advanceCandidate(draft,{toStage:'APPROVED'}),/invalid-stage-transition/));
const shadow=advanceCandidate(draft,{toStage:'SHADOW'});
t(()=>assert.throws(()=>advanceCandidate(shadow,{toStage:'HELD_OUT_VALIDATED',shadowResult:{passed:false}}),/shadow-validation-required/));
const held=advanceCandidate(shadow,{toStage:'HELD_OUT_VALIDATED',shadowResult:{passed:true}});
t(()=>assert.throws(()=>advanceCandidate(held,{toStage:'APPROVED',heldOutResult:{passed:true}}),/explicit-approval-required/));
const approved=advanceCandidate(held,{toStage:'APPROVED',heldOutResult:{passed:true},approval:{approverId:'reviewer-1',timestamp:'2026-08-24T01:00:00Z'}});
t(()=>assert.throws(()=>advanceCandidate(approved,{toStage:'DEPLOYED'}),/monitoring-plan-required/));
const deployed=advanceCandidate(approved,{toStage:'DEPLOYED',monitoringPlan:{metric:'decision-validity',rollbackThreshold:.9}});
t(()=>assert.equal(deployed.stage,'DEPLOYED'));
const suggestion=historicalSuggestion({patternId:'p1',contextSimilarity:.8,observations:[1,2,3]});
t(()=>assert.equal(suggestion.maySatisfyEvidence,false));
t(()=>assert.equal(suggestion.causalClaim,false));
t(()=>assert.equal(suggestion.mayGenerateCandidate,true));
const protectedDraft=createPolicyCandidate({candidateId:'c2',basePolicyVersion:'1',candidateVersion:'2',changes:[{domain:'SAFETY',change:'threshold'}],metricsPlan:{primary:'x'},createdAt:'x'});
t(()=>assert.equal(containsProtectedChange(protectedDraft),true));
const ps=advanceCandidate(protectedDraft,{toStage:'SHADOW'});const ph=advanceCandidate(ps,{toStage:'HELD_OUT_VALIDATED',shadowResult:{passed:true}});const pa=advanceCandidate(ph,{toStage:'APPROVED',heldOutResult:{passed:true},approval:{approverId:'r',timestamp:'x'}});
t(()=>assert.throws(()=>advanceCandidate(pa,{toStage:'DEPLOYED',monitoringPlan:{metric:'x'}}),/protected-change-approval-required/));
const pa2=Object.freeze({...pa,approval:{...pa.approval,protectedChangeApproved:true}});const pd=advanceCandidate(pa2,{toStage:'DEPLOYED',monitoringPlan:{metric:'x'}});
t(()=>assert.equal(pd.stage,'DEPLOYED'));
t(()=>assert.throws(()=>rollbackDeployment(approved,{reason:'x',timestamp:'x'}),/only-deployed-can-rollback/));
const rolled=rollbackDeployment(deployed,{reason:'regression',timestamp:'2026-08-24T02:00:00Z'});
t(()=>assert.equal(rolled.stage,'ROLLED_BACK'));
t(()=>assert.equal(rolled.rollback.reason,'regression'));
console.log(`EEV1 learning governance: PASS (${n} checks)`);
