import assert from 'node:assert/strict';
import {validateResponse,validateReasonCode,reasonSet,ACTION_REJECTION_CODES,NON_ADHERENCE_CODES,ADAPTATION_CODES} from './response-reason-contract.js';
let n=0;const t=f=>{f();n++;};
t(()=>assert.equal(validateResponse({mode:'SINGLE_SELECT',options:['a','b']},{value:'a'}).valid,true));
t(()=>assert.equal(validateResponse({mode:'SINGLE_SELECT',options:['a','b']},{value:'c'}).valid,false));
t(()=>assert.equal(validateResponse({mode:'MULTI_SELECT',options:['a','b']},{value:['a','b']}).valid,true));
t(()=>assert.equal(validateResponse({mode:'MULTI_SELECT',options:['a','b']},{value:['a','a']}).valid,false));
t(()=>assert.equal(validateResponse({mode:'BOOLEAN'},{value:false}).valid,true));
t(()=>assert.equal(validateResponse({mode:'ORDINAL',min:1,max:5},{value:6}).valid,false));
t(()=>assert.equal(validateResponse({mode:'NUMBER',min:0,max:10},{value:4.5}).valid,true));
t(()=>assert.equal(validateResponse({mode:'TEXT',maxLength:5},{value:'abcdef'}).valid,false));
t(()=>assert.equal(validateResponse({mode:'SINGLE_SELECT',options:['a']},{escapeCode:'UNSURE'}).valid,true));
t(()=>assert.equal(validateResponse({mode:'SINGLE_SELECT',options:['a']},{escapeCode:'MAYBE'}).valid,false));
t(()=>assert.equal(validateReasonCode('SAFETY_BLOCK',ACTION_REJECTION_CODES).valid,true));
t(()=>assert.equal(validateReasonCode('FORGOT',NON_ADHERENCE_CODES).valid,true));
t(()=>assert.equal(validateReasonCode('REASSESS_DRIVER',ADAPTATION_CODES).valid,true));
t(()=>assert.equal(validateReasonCode('random',ACTION_REJECTION_CODES).valid,false));
t(()=>assert.equal(reasonSet('nonAdherence').includes('BURDEN_TOO_HIGH'),true));
t(()=>assert.throws(()=>reasonSet('bad'),/unknown-reason-set/));
console.log(`EEV1 response/reason contract: PASS (${n} checks)`);
